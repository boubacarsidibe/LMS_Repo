-- =====================================================================
-- V30 — Grille d'évaluation d'un dossier d'accréditation (TDR §F)
-- =====================================================================
--
-- CONTEXTE
-- criteres_accreditation (V15) porte un référentiel — libellé, description,
-- actif — mais rien ne reliait un critère à un dossier : l'évaluateur le
-- consultait « à côté » sans pouvoir tracer son jugement critère par
-- critère. La décision (avis + accréditer/rejeter) restait un texte libre,
-- non auditable au regard du référentiel.
--
-- evaluation_critere journalise, pour un (dossier, critère, évaluateur),
-- une appréciation CONFORME / NON_CONFORME / SANS_OBJET et un commentaire.
-- Table additive : ni criteres_accreditation ni demandes_accreditation ne
-- sont modifiées. Redéposer met à jour l'entrée existante (même patron que
-- avis_accreditation V20, retour_evaluation V7).
-- =====================================================================

CREATE TABLE public.evaluation_critere (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id      BIGINT       NOT NULL REFERENCES public.demandes_accreditation (id) ON DELETE CASCADE,
    critere_id      BIGINT       NOT NULL REFERENCES public.criteres_accreditation (id) ON DELETE CASCADE,
    evaluateur_id   BIGINT       NOT NULL REFERENCES public.users (id),
    appreciation    VARCHAR(20)  NOT NULL,
    commentaire     VARCHAR(1000),
    date_evaluation TIMESTAMP    NOT NULL DEFAULT now()
);

-- Un jugement par critère et par évaluateur sur un dossier donné : une
-- nouvelle soumission met à jour l'existant (voir
-- EvaluationCritereRepository.findByDemandeIdAndCritereIdAndEvaluateurId).
CREATE UNIQUE INDEX idx_evaluation_critere_unicite
    ON public.evaluation_critere (demande_id, critere_id, evaluateur_id);

CREATE INDEX idx_evaluation_critere_demande
    ON public.evaluation_critere (demande_id);
