-- Releves de notes delivres par la direction pedagogique.
--
-- L'etudiant consultait deja ses notes en continu, mais rien ne constituait un
-- DOCUMENT : ni reference, ni date d'emission, ni trace de ce qui avait ete remis.
-- Le responsable pedagogique, a qui revient la delivrance, n'avait meme aucun moyen
-- de consulter le releve d'un etudiant.
--
-- Les notes sont RECOPIEES a la delivrance, et non recalculees a l'affichage. Un
-- releve remis en janvier ne doit pas changer parce qu'un formateur corrige une note
-- en fevrier : ce serait un ecran, pas un document. C'est la raison d'etre de la
-- table releve_ligne, qui peut donc diverger de note_module — et c'est voulu.

CREATE TABLE public.releve_notes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etudiant_id       BIGINT       NOT NULL,
    promotion_id      BIGINT,
    reference         VARCHAR(64)  NOT NULL UNIQUE,
    periode           VARCHAR(120) NOT NULL,
    date_emission     DATE         NOT NULL,
    delivre_par       VARCHAR(120) NOT NULL,
    -- Figee : NULL si aucune note n'avait ete saisie au moment de la delivrance.
    moyenne_generale  DOUBLE PRECISION,
    nombre_notes      INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_releve_etudiant  FOREIGN KEY (etudiant_id)  REFERENCES public.etudiants (id_user),
    CONSTRAINT fk_releve_promotion FOREIGN KEY (promotion_id) REFERENCES public.promotion (id)
);

CREATE TABLE public.releve_ligne (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    releve_id      BIGINT       NOT NULL,
    cours_code     VARCHAR(64)  NOT NULL,
    cours_titre    VARCHAR(255) NOT NULL,
    coefficient    DOUBLE PRECISION NOT NULL DEFAULT 1,
    moyenne        DOUBLE PRECISION,
    -- Pas de FK vers cours : la ligne doit survivre a la suppression du cours.
    -- Un releve delivre atteste d'un parcours, il ne suit pas l'offre courante.
    CONSTRAINT fk_ligne_releve FOREIGN KEY (releve_id) REFERENCES public.releve_notes (id) ON DELETE CASCADE
);

CREATE INDEX idx_releve_etudiant ON public.releve_notes (etudiant_id);
CREATE INDEX idx_ligne_releve    ON public.releve_ligne (releve_id);
