-- Journal d'étapes d'un dossier de candidature (LOG_BLOQUANT.md, point 64 :
-- alignement sur la procédure qualité QMS-009 « Admission des étudiants et
-- apprenants »). La plateforme ne conservait que l'état courant d'un dossier :
-- ni l'agent qui a fait passer l'étape, ni la date, ni le motif. Un audit
-- qualité ne pouvait donc prouver aucune étape.
--
-- auteur_nom est un cliché figé, pas une jointure : même patron que
-- releve_ligne (migration V9). Un compte supprimé ou renommé ne doit pas
-- réécrire l'historique, sans quoi ce journal cesserait d'être une preuve.
-- auteur_id garde le lien quand le compte existe encore, sans contrainte
-- de cascade destructrice.
CREATE TABLE public.etapes_dossier (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id    BIGINT       NOT NULL REFERENCES public.candidatures(id) ON DELETE CASCADE,
    etape             VARCHAR(30)  NOT NULL,
    statut_resultant  VARCHAR(40),
    auteur_id         BIGINT       REFERENCES public.users(id) ON DELETE SET NULL,
    auteur_nom        VARCHAR(150) NOT NULL,
    date_etape        TIMESTAMP    NOT NULL DEFAULT now(),
    commentaire       VARCHAR(1000)
);

CREATE INDEX idx_etapes_dossier_candidature ON public.etapes_dossier (candidature_id, date_etape);
