-- Suivi des activites du personnel INPG (TDR section I).
--
-- « Cet espace permettra a chaque departement de l'INPG de saisir ses activites
-- mensuelles (formations, projets, recherches, etc.). Un rapport mensuel
-- automatise sera genere pour chaque departement, puis consolide pour obtenir
-- un rapport global de l'ensemble des departements. »
--
-- Le TDR ne fournit ni organigramme ni notion d'affectation d'un utilisateur a
-- un departement : la saisie porte sur « chaque departement », pas sur chaque
-- personne. Modele volontairement minimal — un catalogue de departements et des
-- activites qui y sont rattachees, chacune deposee par un membre du personnel
-- (auteur derive du jeton, jamais transmis par le client) — plutot que
-- d'inventer une hierarchie organisationnelle que rien dans ce depot ne decrit.
--
-- Entierement additive : aucune colonne existante modifiee.

CREATE TABLE public.departements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(50)  NOT NULL UNIQUE,
    libelle        VARCHAR(200) NOT NULL,
    actif          BOOLEAN      NOT NULL DEFAULT TRUE,
    date_creation  TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE public.activites_personnel (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departement_id BIGINT       NOT NULL REFERENCES public.departements (id),
    auteur_id      BIGINT       NOT NULL REFERENCES public.users (id),
    type_activite  VARCHAR(20)  NOT NULL,
    titre          VARCHAR(200) NOT NULL,
    description    VARCHAR(2000),
    mois           INTEGER      NOT NULL,
    annee          INTEGER      NOT NULL,
    date_creation  TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_activite_mois CHECK (mois BETWEEN 1 AND 12)
);

CREATE INDEX idx_activite_departement_periode ON public.activites_personnel (departement_id, annee, mois);
