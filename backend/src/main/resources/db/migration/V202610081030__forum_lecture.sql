-- Messages non lus du forum : pastille numérotée façon WhatsApp.
--
-- Une ligne par (utilisateur, sujet) : l'instant où l'utilisateur a ouvert ce fil
-- pour la dernière fois. Les messages non lus sont ceux postés par un autre, après
-- cet instant. Pas de ligne = jamais ouvert = tout est non lu.
--
-- ON DELETE CASCADE des deux côtés : supprimer un sujet (ou un compte) emporte son
-- suivi de lecture sans qu'aucun code Java n'ait à y penser.

CREATE TABLE public.forum_lecture (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT    NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    sujet_id         BIGINT    NOT NULL REFERENCES public.forum_sujets (id) ON DELETE CASCADE,
    derniere_lecture TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uq_forum_lecture UNIQUE (user_id, sujet_id)
);

CREATE INDEX idx_forum_lecture_sujet ON public.forum_lecture (sujet_id);

-- Point de départ : à la mise en service, tout l'historique existant est réputé lu.
-- Sans cela, chaque utilisateur découvrirait d'un coup autant de « non lus » qu'il
-- y a de messages depuis l'ouverture du forum.
INSERT INTO public.forum_lecture (user_id, sujet_id, derniere_lecture)
SELECT u.id, s.id, now()
FROM public.users u
CROSS JOIN public.forum_sujets s;
