-- Espace Entreprise (TDR section H).
--
-- « La plateforme LMS doit inclure un espace reserve aux entreprises afin de
-- faciliter le dialogue entre les professionnels du secteur et les formateurs
-- de l'INPG. Cet espace permettra aux entreprises de soumettre leurs besoins
-- en matiere de formation [...] de consulter les offres de formation [...]
-- personnaliser les programmes [...] demander des devis et planifier des
-- sessions sur mesure [...] communication directe [...] via un systeme de
-- messagerie securise. »
--
-- Une entreprise EST un utilisateur, meme patron @MapsId que Candidat/
-- Etudiant/EcoleFormation/AlumniProfil : entreprises partage sa cle primaire
-- avec users. Le role ROLE_ENTREPRISE n'est accorde qu'a la premiere
-- soumission reussie (meme patron que ROLE_ECOLE_FORMATION), pas a
-- l'inscription elle-meme.
--
-- Une seule entite demandes_entreprise couvre a la fois le "besoin de
-- formation" et la "demande de devis/session sur mesure" du TDR (colonne
-- type) : les deux partagent la meme mecanique (description, statut, reponse
-- de l'equipe pedagogique) et n'auraient differe que par deux colonnes
-- optionnelles (effectif, dates souhaitees) - deux entites quasi-identiques
-- auraient duplique toute la logique de suivi pour rien.
--
-- La messagerie n'est PAS une extension de la portee du forum existant
-- (forum_sujet.portee) : ce forum est un espace *partage* entre plusieurs
-- participants d'une meme portee (tous les alumni, tous les etudiants d'un
-- cours...), alors qu'ici chaque entreprise doit avoir un canal *prive*,
-- visible uniquement d'elle-meme et de l'equipe pedagogique - reutiliser le
-- forum aurait exige d'y inventer une notion de canal 1:1 qui n'existe pas,
-- pour un besoin plus simple a modeliser directement.

CREATE TABLE public.entreprises (
    id_user       BIGINT PRIMARY KEY REFERENCES public.users (id),
    raison_sociale VARCHAR(200) NOT NULL,
    secteur       VARCHAR(150),
    adresse       VARCHAR(300) NOT NULL,
    telephone     VARCHAR(30)  NOT NULL,
    date_creation DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE public.demandes_entreprise (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entreprise_id     BIGINT       NOT NULL REFERENCES public.entreprises (id_user),
    type              VARCHAR(20)  NOT NULL,
    formation_id      BIGINT       REFERENCES public.formation (id),
    description       VARCHAR(2000) NOT NULL,
    effectif_concerne INTEGER,
    dates_souhaitees  VARCHAR(200),
    statut            VARCHAR(20)  NOT NULL DEFAULT 'SOUMISE',
    date_soumission   TIMESTAMP    NOT NULL DEFAULT now(),
    date_reponse      TIMESTAMP,
    reponse_equipe    VARCHAR(2000)
);

-- Canal prive par entreprise : l'equipe pedagogique voit tous les messages
-- (filtre par entreprise_id cote application), l'entreprise ne voit que les
-- siens (filtre par son propre id_user).
CREATE TABLE public.messages_entreprise (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entreprise_id  BIGINT      NOT NULL REFERENCES public.entreprises (id_user),
    auteur_id      BIGINT      NOT NULL REFERENCES public.users (id),
    contenu        VARCHAR(2000) NOT NULL,
    date_creation  TIMESTAMP   NOT NULL DEFAULT now()
);

CREATE INDEX idx_demandes_entreprise_entreprise ON public.demandes_entreprise (entreprise_id);
CREATE INDEX idx_messages_entreprise_entreprise ON public.messages_entreprise (entreprise_id);
