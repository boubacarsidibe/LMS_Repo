-- Processus qualite (TDR section G) : volet « enquetes de suivi ».
--
-- « De plus, des enquetes de suivi devront etre disponibles pour mesurer l'impact
-- a long terme de la formation sur la carriere des diplomes. » + besoin specifique
-- « Systeme de suivi des etudiants apres leur formation pour recueillir des retours
-- sur l'application des competences dans leur travail. »
--
-- Distinct de situations_professionnelles (V12) : celle-ci est un historique de
-- poste librement tenu par l'alumni (intitule, entreprise, dates), jamais une
-- question posee par l'INPG. Une enquete_suivi est une campagne lancee par la
-- pedagogie (une ligne par campagne, pas par alumni) ; chaque alumni y repond au
-- plus une fois (contrainte unique), sur les deux dimensions explicitement
-- demandees par le TDR : application des competences, et impact sur la carriere.
--
-- Distinct aussi de retour_evaluation (avis sur UN cours, depose par un etudiant
-- inscrit) : une enquete_suivi porte sur la formation dans son ensemble, apres
-- coup, deposee par un alumni.

CREATE TABLE public.enquetes_suivi (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre          VARCHAR(200)  NOT NULL,
    description    VARCHAR(1000),
    date_creation  TIMESTAMP     NOT NULL DEFAULT now(),
    active         BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE public.reponses_enquete_suivi (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enquete_id                     BIGINT       NOT NULL REFERENCES public.enquetes_suivi (id),
    alumni_profil_id               BIGINT       NOT NULL REFERENCES public.alumni_profils (id_user),
    note_application_competences   INTEGER      NOT NULL,
    note_impact_carriere           INTEGER      NOT NULL,
    commentaire                    VARCHAR(2000),
    date_reponse                   TIMESTAMP    NOT NULL DEFAULT now(),
    UNIQUE (enquete_id, alumni_profil_id)
);

CREATE INDEX idx_reponse_enquete_alumni ON public.reponses_enquete_suivi (alumni_profil_id);
CREATE INDEX idx_reponse_enquete_enquete ON public.reponses_enquete_suivi (enquete_id);
