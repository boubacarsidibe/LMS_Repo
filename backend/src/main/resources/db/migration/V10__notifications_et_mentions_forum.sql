-- Notifications dans l'application, et mentions au forum.
--
-- Une cloche existait deja, mais adossee au CANDIDAT (notifications_candidat) :
-- inutilisable pour un etudiant ou un formateur. Les relances collectives du
-- responsable pedagogique partaient donc uniquement par courriel, faute de canal
-- interne — le commentaire de PedagogieScolariteController le disait deja.
--
-- Cette table est adossee a l'UTILISATEUR : elle sert indifferemment l'etudiant, le
-- formateur et le responsable pedagogique. La table candidat reste en place, son
-- espace ayant son propre parcours.
--
-- Choix du canal : la mention est frequente et de faible enjeu. Un courriel a chaque
-- fois inonderait la boite, l'utilisateur couperait la notification, et elle cesserait
-- de servir. L'action est d'ailleurs dans l'application — on clique, on arrive sur le
-- fil.

CREATE TABLE public.notification (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    message        VARCHAR(500) NOT NULL,
    -- MENTION_FORUM aujourd'hui ; le champ reste ouvert pour les usages a venir.
    type           VARCHAR(64)  NOT NULL,
    lu             BOOLEAN      NOT NULL DEFAULT FALSE,
    date_creation  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Ou mene la notification. Sans lien, elle informe sans permettre d'agir.
    lien           VARCHAR(255),
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE CASCADE
);

-- La cloche interroge « mes notifications non lues » a chaque chargement d'ecran.
CREATE INDEX idx_notification_destinataire ON public.notification (user_id, lu);

-- Qui est cite dans quel message.
--
-- Stockee plutot que rededuite du texte a l'affichage : un nom peut etre ecrit de
-- plusieurs manieres, changer, ou apparaitre par hasard dans une phrase. Relire le
-- texte pour retrouver les mentions donnerait des resultats differents selon le
-- moment — ici la citation est un fait, etabli une fois a la publication.
CREATE TABLE public.forum_mention (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id  BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    CONSTRAINT fk_mention_message FOREIGN KEY (message_id) REFERENCES public.forum_messages (id) ON DELETE CASCADE,
    CONSTRAINT fk_mention_user    FOREIGN KEY (user_id)    REFERENCES public.users (id) ON DELETE CASCADE,
    -- Citer deux fois la meme personne dans un message ne la notifie qu'une fois.
    CONSTRAINT uq_mention_message_user UNIQUE (message_id, user_id)
);

CREATE INDEX idx_mention_message ON public.forum_mention (message_id);
