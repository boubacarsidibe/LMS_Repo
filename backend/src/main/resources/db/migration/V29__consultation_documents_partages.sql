-- Trace de consultation d'un document partagé alumni (LOG_BLOQUANT.md, epic
-- "profil alumni enrichi" du 2026-08-28) : les métriques du profil comptaient
-- les documents déposés par l'alumni, jamais ceux qu'il a réellement ouverts,
-- faute de tout suivi de lecture pour ce module.
--
-- Même patron que progressions_support (baseline) : une ligne par lecteur et
-- par document, posée à la première ouverture et jamais mise à jour ensuite.
-- lecteur_id référence users(id) et non alumni_profils(id_user) : un document
-- de l'espace alumni pourrait un jour être ouvert par un autre rôle qui y a
-- accès (aucun cas aujourd'hui, mais rien n'empêche cette table de servir sans
-- migration supplémentaire le jour où ça change).

CREATE TABLE public.consultations_document_partage (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT    NOT NULL REFERENCES public.documents_partages(id) ON DELETE CASCADE,
    lecteur_id     BIGINT    NOT NULL REFERENCES public.users(id),
    date_consultation TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uk_consultation_document_lecteur UNIQUE (document_id, lecteur_id)
);

CREATE INDEX idx_consultations_document_lecteur ON public.consultations_document_partage (lecteur_id);
