-- Partage de documents entre alumni (TDR section C, seconde moitié : « la
-- possibilité de partager des documents »).
--
-- Un seul espace de partage, plat, ouvert a tous les alumni : AlumniProfil ne
-- porte pas de promotion (un alumni a termine sa scolarite active, cf. migration
-- V12), donc rien ne permettrait de stratifier par promotion comme le suggerait
-- l'esquisse initiale du modele cible (docs/uml/release-2-enrichissement-
-- pedagogique.drawio, case DocumentPartage — champ visiblePar). Le TDR ne demande
-- d'ailleurs aucune stratification. Si un besoin reel de portee plus fine apparait,
-- ce sera une colonne additive, pas une refonte.
--
-- Stockage : meme mecanisme que la photheque et les pieces jointes du forum
-- (PhotoStorageService/ValidationFichier) — pas de nouveau systeme de fichiers.
-- Le fichier lui-meme n'est jamais servi de maniere statique (WebConfig ne sert
-- que le sous-dossier "public") : le telechargement passe par un endpoint
-- authentifie, hasRole('ALUMNI').

CREATE TABLE public.documents_partages (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auteur_id              BIGINT       NOT NULL REFERENCES public.users(id),
    titre                  VARCHAR(200) NOT NULL,
    description            VARCHAR(1000),
    nom_fichier_original   VARCHAR(255) NOT NULL,
    nom_fichier_stocke     VARCHAR(255) NOT NULL,
    type_contenu           VARCHAR(100),
    date_ajout             TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE INDEX idx_documents_partages_auteur ON public.documents_partages (auteur_id);
