-- Modules, devoirs et évaluations gérés par le formateur pour les seuls cours attribués.
CREATE TABLE activite_cours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cours_id BIGINT NOT NULL REFERENCES cours(id) ON DELETE CASCADE,
    auteur_id BIGINT NOT NULL REFERENCES formateurs(id_user),
    module VARCHAR(255) NOT NULL,
    titre VARCHAR(255) NOT NULL,
    description TEXT,
    type VARCHAR(32) NOT NULL,
    modalite VARCHAR(32) NOT NULL,
    date_publication TIMESTAMP NOT NULL,
    date_limite TIMESTAMP,
    bareme NUMERIC(5,2) NOT NULL DEFAULT 100,
    cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modifie_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_activite_cours_publication ON activite_cours(cours_id, date_publication);

CREATE TABLE remise_activite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activite_id BIGINT NOT NULL REFERENCES activite_cours(id) ON DELETE CASCADE,
    etudiant_id BIGINT NOT NULL REFERENCES etudiants(id_user),
    contenu TEXT,
    remise_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note NUMERIC(5,2),
    commentaire_correction TEXT,
    corrige_le TIMESTAMP,
    UNIQUE (activite_id, etudiant_id)
);

CREATE INDEX idx_remise_activite_etudiant ON remise_activite(etudiant_id, activite_id);
