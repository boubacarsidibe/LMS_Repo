-- Critères d'admission personnalisables (LOG_BLOQUANT.md, epic "critères
-- d'admission personnalisables" du 2026-09-02) : SessionCandidature ne portait
-- que des critères fixes codés en dur (niveau d'étude, âge, genre, expérience),
-- évalués par un `if` par champ dans respecteCriteres(). Le responsable
-- admission ne pouvait en ajouter aucun sans une migration de code.
--
-- Une session porte désormais une liste ouverte de critères, affichés sur le
-- formulaire de candidature en plus des critères de base. `actif=false` est
-- un retrait logique (jamais de suppression physique) : un critère déjà
-- répondu par des candidats ne doit pas faire disparaître ces réponses sous
-- un admin qui a simplement cessé de le proposer aux nouvelles candidatures.
CREATE TABLE public.criteres_admission_personnalises (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_candidature_id  BIGINT NOT NULL REFERENCES public.sessions_candidature(id) ON DELETE CASCADE,
    libelle                 VARCHAR(150) NOT NULL,
    type                    VARCHAR(20) NOT NULL,
    obligatoire             BOOLEAN NOT NULL DEFAULT true,
    options                 VARCHAR(500),
    valeur_minimale         INTEGER,
    valeur_attendue         VARCHAR(255),
    ordre                   INTEGER NOT NULL DEFAULT 0,
    actif                   BOOLEAN NOT NULL DEFAULT true
);

CREATE INDEX idx_criteres_personnalises_session ON public.criteres_admission_personnalises (session_candidature_id);

-- Réponse du candidat à un critère personnalisé, une ligne par (candidature,
-- critère). Rattachée à la candidature (pas au candidat) : un candidat qui
-- redépose sur une nouvelle session répond à nouveau, la session pouvant
-- avoir changé ses critères entre-temps.
CREATE TABLE public.reponses_critere_candidature (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id BIGINT NOT NULL REFERENCES public.candidatures(id) ON DELETE CASCADE,
    critere_id     BIGINT NOT NULL REFERENCES public.criteres_admission_personnalises(id) ON DELETE CASCADE,
    valeur         VARCHAR(500),
    CONSTRAINT uk_reponse_candidature_critere UNIQUE (candidature_id, critere_id)
);

CREATE INDEX idx_reponses_critere_candidature ON public.reponses_critere_candidature (candidature_id);
