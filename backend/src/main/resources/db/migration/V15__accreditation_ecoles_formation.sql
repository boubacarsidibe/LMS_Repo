-- Accreditation des ecoles de formation (TDR section F).
--
-- « La plateforme LMS doit integrer un module dedie a l'accreditation des ecoles
-- de formation souhaitant dispenser des formations dans le domaine du petrole et
-- du gaz. Ce module permettra aux ecoles de creer un compte, de soumettre leurs
-- demandes d'accreditation [...] et de suivre l'etat de leur demande [...].
-- La plateforme devra egalement permettre de definir et de gerer les criteres
-- d'accreditation, avec un espace reserve aux evaluateurs [...]. »
--
-- Une ecole EST un utilisateur (patron @MapsId deja suivi par Candidat/Etudiant/
-- AlumniProfil) : ecoles_formation partage sa cle primaire avec users, exactement
-- comme les autres profils. Le role ROLE_EVALUATEUR_ACCREDITATION est un role a
-- part entiere (voir DataInitializer), assignable via l'ecran generique existant
-- de gestion des roles (PUT /api/admin/users/{id}/roles) - aucun nouvel endpoint
-- d'attribution de role n'etait necessaire.
--
-- Les documents joints reutilisent fichiers_stockes (V1, module recrutement) :
-- une piece d'accreditation est une ligne pieces_accreditation qui reference un
-- fichier_stocke existant, exactement comme pieces_justificatives le fait deja
-- pour les dossiers de candidature. Pas de nouveau mecanisme de fichiers.
--
-- Pas de numero de dossier genere (contrairement a Candidature.numeroDossier) :
-- l'identifiant technique suffit ici, aucune consigne du TDR n'exige un numero
-- lisible pour ce module.

CREATE TABLE public.ecoles_formation (
    id_user       BIGINT PRIMARY KEY REFERENCES public.users (id),
    nom_ecole     VARCHAR(200) NOT NULL,
    adresse       VARCHAR(300) NOT NULL,
    telephone     VARCHAR(30)  NOT NULL,
    site_web      VARCHAR(300),
    date_creation DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE public.demandes_accreditation (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ecole_id              BIGINT       NOT NULL REFERENCES public.ecoles_formation (id_user),
    statut                VARCHAR(30)  NOT NULL DEFAULT 'SOUMISE',
    date_soumission       TIMESTAMP    NOT NULL DEFAULT now(),
    date_decision         TIMESTAMP,
    motif_rejet           VARCHAR(1000),
    commentaire_evaluation VARCHAR(1000),
    evaluateur_id         BIGINT REFERENCES public.users (id)
);

-- Une ecole ne peut avoir qu'une seule demande active a la fois (pas encore
-- ACCREDITE ni REJETE) : sans cette contrainte, rien n'empecherait un depot
-- multiple pendant qu'un dossier est deja en cours d'evaluation. Realisee par un
-- index partiel plutot qu'une contrainte UNIQUE simple, pour laisser une ecole
-- deja rejetee redeposer un dossier.
CREATE UNIQUE INDEX idx_demande_active_unique ON public.demandes_accreditation (ecole_id)
    WHERE statut IN ('SOUMISE', 'EN_COURS_EVALUATION');

CREATE TABLE public.pieces_accreditation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_document    VARCHAR(40) NOT NULL,
    demande_id       BIGINT      NOT NULL REFERENCES public.demandes_accreditation (id) ON DELETE CASCADE,
    fichier_stocke_id BIGINT     REFERENCES public.fichiers_stockes (id)
);

CREATE TABLE public.criteres_accreditation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle     VARCHAR(200) NOT NULL,
    description VARCHAR(500),
    actif       BOOLEAN      NOT NULL DEFAULT true
);
