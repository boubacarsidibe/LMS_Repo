-- =====================================================================
-- V20 — Avis multiples sur une demande d'accréditation (TDR §F)
-- =====================================================================
--
-- CONTEXTE
-- Le TDR §F prévoit « un espace réservé aux évaluateurs afin qu'ils
-- puissent consulter les informations soumises et rendre leurs décisions »
-- — au pluriel. Jusqu'ici, une seule paire de colonnes portait l'avis
-- (evaluateur_id, commentaire_evaluation, motif_rejet sur
-- demandes_accreditation), écrasée par quiconque tranchait en premier :
-- aucune trace des avis des autres évaluateurs n'était conservée.
--
-- avis_accreditation journalise un avis par (demande, évaluateur) — table
-- additive, aucune colonne de demandes_accreditation n'est touchée ni
-- supprimée. La décision finale (accrediter/rejeter) reste un acte
-- explicite d'un évaluateur, désormais exigé de s'appuyer sur au moins un
-- avis déjà déposé plutôt que de trancher à l'aveugle.
-- =====================================================================

CREATE TABLE public.avis_accreditation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id    BIGINT       NOT NULL REFERENCES public.demandes_accreditation (id) ON DELETE CASCADE,
    evaluateur_id BIGINT       NOT NULL REFERENCES public.users (id),
    avis          VARCHAR(20)  NOT NULL,
    commentaire   VARCHAR(1000),
    date_avis     TIMESTAMP    NOT NULL DEFAULT now()
);

-- Un évaluateur ne dépose qu'un avis par demande : une nouvelle soumission
-- met à jour l'existant plutôt que d'en empiler un second (voir
-- AvisAccreditationRepository.findByDemandeIdAndEvaluateurId).
CREATE UNIQUE INDEX idx_avis_accreditation_demande_evaluateur
    ON public.avis_accreditation (demande_id, evaluateur_id);
