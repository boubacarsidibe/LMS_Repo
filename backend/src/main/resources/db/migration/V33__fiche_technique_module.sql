-- =====================================================================
-- V33 — Fiche Technique de Module pour une formation d'entreprise sur mesure
-- =====================================================================
--
-- CONTEXTE
-- Le document « FICHE TECHNIQUE MODULE » de l'INPG (gabarit en 10 sections,
-- exemple : lubrification des machines tournantes pour la SAR) est le livrable
-- que la Direction Pédagogique et Ingénierie (DPI) produit en réponse à une
-- demande d'entreprise « devis / session sur mesure » (TDR §H ; procédures
-- QMS-006, QMS-008, QMS-010). L'espace entreprise ne portait qu'une réponse en
-- texte libre : aucune structure, rien à accepter formellement.
--
-- fiche_technique_module : une fiche par demande d'entreprise (1:1, index
-- unique). fiche_module_jour : le planning jour par jour (§4), seul bloc
-- réellement répétitif du gabarit. Les autres sections restent du texte —
-- le document lui-même est de la prose.
-- =====================================================================

CREATE TABLE public.fiche_technique_module (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demande_id               BIGINT       NOT NULL UNIQUE
                                 REFERENCES public.demandes_entreprise (id) ON DELETE CASCADE,

    -- En-tête
    code                     VARCHAR(60),
    intitule                 VARCHAR(300),
    version                  VARCHAR(30),
    date_revision            DATE,
    responsable_module       VARCHAR(200),

    -- §1 Caractéristiques des cibles à former
    departement              VARCHAR(200),
    atelier_service          VARCHAR(200),
    fonctions_cibles         VARCHAR(500),
    thematiques              VARCHAR(500),
    prerequis                VARCHAR(1000),
    langue                   VARCHAR(60)   DEFAULT 'Français',
    niveau                   VARCHAR(120),
    effectif                 INTEGER,
    duree_heures             INTEGER,
    duree_jours              INTEGER,
    periode_probable         VARCHAR(120),

    -- §2 Objectifs d'apprentissage
    objectif_general         VARCHAR(2000),
    objectifs_specifiques    VARCHAR(4000),

    -- §3 Modalités de test de prérequis
    modalites_test_prerequis VARCHAR(2000),

    -- §5 Formation sur site
    formation_sur_site       VARCHAR(1000),

    -- §6 Types d'évaluation
    types_evaluation         VARCHAR(2000),

    -- §7 Ressources pédagogiques
    ressources_pedagogiques  VARCHAR(2000),

    -- §8 Bibliographie
    bibliographie            VARCHAR(2000),

    -- §9 Profil / expérience des formateurs
    profil_formateur         VARCHAR(2000),

    -- Proposition financière (QMS-008 : offre technique ET financière)
    cout_total               VARCHAR(120),
    modalites_financieres    VARCHAR(1000),

    -- §10 Validation / cycle de vie
    statut                   VARCHAR(30)  NOT NULL DEFAULT 'BROUILLON',
    date_creation            TIMESTAMP    NOT NULL DEFAULT now(),
    date_transmission        TIMESTAMP,
    commentaire_entreprise   VARCHAR(2000),
    date_decision_entreprise TIMESTAMP
);

CREATE TABLE public.fiche_module_jour (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fiche_id          BIGINT       NOT NULL REFERENCES public.fiche_technique_module (id) ON DELETE CASCADE,
    numero            INTEGER      NOT NULL,
    contenus          VARCHAR(2000),
    duree_heures      INTEGER,
    type_enseignement VARCHAR(200),
    modalites         VARCHAR(500)
);

CREATE INDEX idx_fiche_module_jour_fiche ON public.fiche_module_jour (fiche_id);
