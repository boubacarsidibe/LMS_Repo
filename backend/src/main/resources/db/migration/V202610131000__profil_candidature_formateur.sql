-- =====================================================================
-- V202610131000 — Dossier de candidature formateur enrichi (inspiré SuccessFactors)
-- =====================================================================
--
-- NUMÉROTATION
-- Écrite sur la branche codespace-literate-system sous le nom V39, rapatriée sur develop le 2026-10-13 :
-- V39 y est déjà prise, et une version plus basse que les migrations déjà appliquées serait refusée par
-- Flyway (hors ordre). D'où cet horodatage ; le contenu est celui du commit ab7b5ae, inchangé.
--
-- CONTEXTE
-- Le dépôt d'une candidature (V48) ne portait que l'identité minimale
-- (nom/prénom/téléphone), un diplôme en texte libre, un nombre d'années
-- d'expérience et une lettre de motivation — plus pauvre que le dossier RH
-- que l'INPG souhaite désormais recueillir (état civil, adresse, formations
-- et expériences professionnelles répétables avec référence du supérieur,
-- langues, certifications, domaines d'expertise), sur le modèle d'un portail
-- de recrutement de référence (SAP SuccessFactors).
--
-- Toutes les colonnes et tables ajoutées ici sont facultatives : seuls
-- nom/prénom/téléphone (déjà là depuis V48) restent obligatoires au dépôt.
-- Patron repris de pieces_candidature_formateur (V48) pour les quatre
-- tables répétables : FK vers candidatures_formateur, ON DELETE CASCADE.
-- =====================================================================

-- ---------- 1. État civil et adresse (candidatures_formateur) ----------
ALTER TABLE public.candidatures_formateur
    ADD COLUMN civilite              VARCHAR(20),
    ADD COLUMN genre                 VARCHAR(20),
    ADD COLUMN date_naissance        DATE,
    ADD COLUMN pays_naissance        VARCHAR(100),
    ADD COLUMN lieu_naissance        VARCHAR(150),
    ADD COLUMN nationalite           VARCHAR(100),
    ADD COLUMN nationalite_secondaire VARCHAR(100),
    ADD COLUMN niveau_etude          VARCHAR(150),
    ADD COLUMN telephone_secondaire  VARCHAR(30),
    ADD COLUMN email_alternatif      VARCHAR(200),
    ADD COLUMN adresse_ligne1        VARCHAR(200),
    ADD COLUMN adresse_ligne2        VARCHAR(200),
    ADD COLUMN ville                 VARCHAR(120),
    ADD COLUMN pays_residence        VARCHAR(100);

-- ---------- 2. Formations (répétable) ----------
CREATE TABLE public.formations_candidature_formateur (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id     BIGINT      NOT NULL REFERENCES public.candidatures_formateur (id) ON DELETE CASCADE,
    niveau_etude       VARCHAR(150),
    pays               VARCHAR(100),
    ville              VARCHAR(120),
    etablissement      VARCHAR(200),
    intitule_diplome   VARCHAR(200),
    matiere_principale VARCHAR(200),
    date_debut         DATE,
    date_obtention     DATE
);

CREATE INDEX idx_formation_candidature_formateur_candidature
    ON public.formations_candidature_formateur (candidature_id);

-- ---------- 3. Expériences professionnelles (répétable, avec référence) ----------
CREATE TABLE public.experiences_candidature_formateur (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id        BIGINT      NOT NULL REFERENCES public.candidatures_formateur (id) ON DELETE CASCADE,
    employeur             VARCHAR(200),
    pays                  VARCHAR(100),
    ville                 VARCHAR(120),
    poste_actuel          BOOLEAN     NOT NULL DEFAULT false,
    intitule_poste        VARCHAR(200),
    date_debut            DATE,
    date_fin              DATE,
    nom_superviseur       VARCHAR(200),
    titre_superviseur     VARCHAR(200),
    telephone_superviseur VARCHAR(30),
    email_superviseur     VARCHAR(200),
    contact_autorise      BOOLEAN,
    motif_non_contact     VARCHAR(500),
    motif_depart          VARCHAR(500)
);

CREATE INDEX idx_experience_candidature_formateur_candidature
    ON public.experiences_candidature_formateur (candidature_id);

-- ---------- 4. Langues (répétable) ----------
CREATE TABLE public.langues_candidature_formateur (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id BIGINT      NOT NULL REFERENCES public.candidatures_formateur (id) ON DELETE CASCADE,
    langue         VARCHAR(100) NOT NULL,
    niveau         VARCHAR(20)  NOT NULL
);

CREATE INDEX idx_langue_candidature_formateur_candidature
    ON public.langues_candidature_formateur (candidature_id);

-- ---------- 5. Certifications (répétable) ----------
CREATE TABLE public.certifications_candidature_formateur (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id  BIGINT      NOT NULL REFERENCES public.candidatures_formateur (id) ON DELETE CASCADE,
    intitule        VARCHAR(200) NOT NULL,
    organisme       VARCHAR(200),
    date_obtention  DATE,
    date_expiration DATE
);

CREATE INDEX idx_certification_candidature_formateur_candidature
    ON public.certifications_candidature_formateur (candidature_id);

-- ---------- 6. Domaines d'expertise (collection simple, pas d'entité propre) ----------
-- Les valeurs viennent du catalogue existant (offres_recrutement_formateur.domaine,
-- formation.domaine) exposé en direct par l'API : aucune nouvelle liste à
-- maintenir ici, pas de contrainte de référence sur une table de domaines.
CREATE TABLE public.candidature_formateur_domaines_expertise (
    candidature_id BIGINT      NOT NULL REFERENCES public.candidatures_formateur (id) ON DELETE CASCADE,
    domaine        VARCHAR(120) NOT NULL
);

CREATE INDEX idx_candidature_formateur_domaine_candidature
    ON public.candidature_formateur_domaines_expertise (candidature_id);
