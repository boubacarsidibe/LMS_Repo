CREATE TABLE conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant1_id BIGINT NOT NULL REFERENCES users(id),
    participant2_id BIGINT NOT NULL REFERENCES users(id),
    date_creation TIMESTAMP NOT NULL
);

CREATE TABLE message_prive (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversation(id) ON DELETE CASCADE,
    auteur_id BIGINT NOT NULL REFERENCES users(id),
    contenu TEXT NOT NULL,
    date_envoi TIMESTAMP NOT NULL,
    lu BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_message_prive_conversation ON message_prive(conversation_id);
CREATE INDEX idx_conversation_participant1 ON conversation(participant1_id);
CREATE INDEX idx_conversation_participant2 ON conversation(participant2_id);
