-- =====================================================================
-- V38 — Recrutement des formateurs (procédure QMS-007)
-- =====================================================================
--
-- CONTEXTE
-- La procédure QMS-007 « Recrutement des formateurs » du SMQ de l'INPG :
-- fiche de poste (§1) → diffusion (§2) → réception et tri des candidatures
-- (§3) → sélection et recrutement (§4). Jusqu'ici un formateur était créé
-- d'un seul geste par le responsable pédagogique (PedagogieController#creerFormateur),
-- sans offre ni candidature.
--
-- Ce lot couvre : offre de poste → candidature avec pièces → suivi en 3 états
-- (DOSSIER_RECU → EN_COURS_DE_TRAITEMENT → TERMINE) → décision (RETENU / NON_RETENU)
-- → création du compte formateur. Le pilote est le RESPONSABLE_ADMISSION
-- (décision produit : pas de rôle DAF/RH distinct).
--
-- Réutilise fichiers_stockes (module recrutement) pour les pièces jointes,
-- exactement comme pieces_accreditation (V15) et pieces_justificatives.
-- Le rôle ROLE_CANDIDAT_FORMATEUR est amorcé côté Java (DataInitializer),
-- comme tous les autres rôles.
-- =====================================================================

-- ---------- 1. Fiche de poste (QMS-007 §1) ----------
CREATE TABLE public.offres_recrutement_formateur (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intitule                 VARCHAR(200) NOT NULL,
    domaine                  VARCHAR(120),
    description_missions      VARCHAR(4000),
    profil_recherche         VARCHAR(4000),
    type_contrat             VARCHAR(20)  NOT NULL,
    lieu                     VARCHAR(200),
    nb_postes                INTEGER      NOT NULL DEFAULT 1,
    formation_id             BIGINT       REFERENCES public.formation (id),
    date_publication         DATE,
    date_limite_candidature  DATE,
    statut                   VARCHAR(20)  NOT NULL DEFAULT 'BROUILLON',
    date_creation            TIMESTAMP    NOT NULL DEFAULT now(),
    cree_par_user_id         BIGINT       REFERENCES public.users (id)
);

-- ---------- 2. Candidature (QMS-007 §3-4) ----------
CREATE TABLE public.candidatures_formateur (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offre_id            BIGINT       NOT NULL REFERENCES public.offres_recrutement_formateur (id),
    candidat_user_id    BIGINT       NOT NULL REFERENCES public.users (id),
    nom                 VARCHAR(120) NOT NULL,
    prenom              VARCHAR(120) NOT NULL,
    email               VARCHAR(200) NOT NULL,
    telephone           VARCHAR(30)  NOT NULL,
    diplome_principal   VARCHAR(300),
    annees_experience   INTEGER,
    lettre_motivation   VARCHAR(4000),
    statut              VARCHAR(30)  NOT NULL DEFAULT 'DOSSIER_RECU',
    decision            VARCHAR(20),
    motif_decision      VARCHAR(2000),
    date_soumission     TIMESTAMP    NOT NULL DEFAULT now(),
    date_decision       TIMESTAMP,
    traite_par_user_id  BIGINT       REFERENCES public.users (id),
    formateur_cree      BOOLEAN      NOT NULL DEFAULT false
);

-- Une seule candidature active (non terminée) par (offre, candidat) : sans cet
-- index partiel, rien n'empêcherait un dépôt multiple sur la même offre pendant
-- l'instruction. Patron idx_demande_active_unique (V15).
CREATE UNIQUE INDEX idx_candidature_formateur_active_unique
    ON public.candidatures_formateur (offre_id, candidat_user_id)
    WHERE statut <> 'TERMINE';

CREATE INDEX idx_candidature_formateur_offre ON public.candidatures_formateur (offre_id);
CREATE INDEX idx_candidature_formateur_candidat ON public.candidatures_formateur (candidat_user_id);

-- ---------- 3. Pièces jointes ----------
CREATE TABLE public.pieces_candidature_formateur (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidature_id    BIGINT      NOT NULL REFERENCES public.candidatures_formateur (id) ON DELETE CASCADE,
    type_document     VARCHAR(40) NOT NULL,
    fichier_stocke_id BIGINT      REFERENCES public.fichiers_stockes (id)
);

CREATE INDEX idx_piece_candidature_formateur_candidature
    ON public.pieces_candidature_formateur (candidature_id);
