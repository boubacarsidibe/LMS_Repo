-- Espace Alumni (TDR section C).
--
-- « La plateforme doit comprendre une section dédiée aux Alumni afin de regrouper
-- les anciens étudiants de l'INPG avec la possibilité d'avoir un suivi de leur
-- situation professionnelle. Ces utilisateurs devront avoir accès à leurs relevés
-- et autres informations qui seront définies par l'INPG. »
--
-- Un alumni EST un étudiant (patron @MapsId deja suivi par candidats/etudiants) :
-- alumni_profils partage sa cle primaire avec users, exactement comme etudiants et
-- candidats. La ligne etudiants n'est PAS supprimee au passage alumni (meme logique
-- que candidats conservee apres le passage etudiant, cf. AdminRecrutementController)
-- : c'est ce qui permet a l'alumni de continuer a lire son relevé de notes délivré
-- (releve_notes.etudiant_id pointe toujours vers une ligne etudiants valide).
--
-- Le forum et le partage de documents demandes par la meme section du TDR ne sont
-- pas couverts par cette migration : ForumSujet n'a aujourd'hui aucune notion de
-- portee (etudiant seul / alumni seul) au-dela du rattachement a un cours, et
-- l'etendre demande une decision de modele a part entiere (voir LOG_BLOQUANT.md).

CREATE TABLE public.alumni_profils (
    id_user           BIGINT PRIMARY KEY REFERENCES public.users (id),
    poste_actuel      VARCHAR(255),
    entreprise        VARCHAR(255),
    secteur_activite  VARCHAR(255),
    visible           BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation     DATE    NOT NULL DEFAULT CURRENT_DATE
);

-- Historique des postes, et non un simple champ : un alumni change d'employeur
-- plusieurs fois, chaque ligne fige un poste occupé (meme principe que releve_ligne
-- pour un releve : figer une valeur n'est pas la recalculer).
CREATE TABLE public.situations_professionnelles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumni_profil_id   BIGINT       NOT NULL,
    intitule_poste     VARCHAR(255) NOT NULL,
    entreprise         VARCHAR(255) NOT NULL,
    date_debut         DATE         NOT NULL,
    date_fin           DATE,
    CONSTRAINT fk_situation_alumni FOREIGN KEY (alumni_profil_id)
        REFERENCES public.alumni_profils (id_user) ON DELETE CASCADE
);

CREATE INDEX idx_situation_alumni ON public.situations_professionnelles (alumni_profil_id);
