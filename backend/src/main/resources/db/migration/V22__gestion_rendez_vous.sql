-- Gestion des rendez-vous (TDR section J).
--
-- « La plateforme doit integrer un espace dedie a la gestion des demandes de
-- rendez-vous en ligne ou en presentiel. Chaque utilisateur pourra consulter
-- le profil des membres du personnel de l'INPG et envoyer une demande de
-- rendez-vous en choisissant un creneau disponible dans leur emploi du temps.
-- L'outil doit etre connecte aux calendriers individuels de chaque membre du
-- personnel, de sorte que seuls les creneaux libres soient visibles par
-- l'utilisateur. Les membres du personnel auront la possibilite d'accepter,
-- de refuser ou de proposer une autre date pour le rendez-vous. »
--
-- Aucune notion de calendrier/disponibilite n'existe ailleurs dans ce depot.
-- Modele retenu (voir LOG_BLOQUANT.md) : chaque membre du personnel publie
-- lui-meme des creneaux ponctuels (pas de moteur de recurrence hebdomadaire,
-- non demande par le TDR et hors de portee d'une story raisonnable) ; un
-- creneau reserve n'apparait plus comme libre tant que la demande qui le
-- couvre n'est pas refusee. Entierement additive : aucune colonne existante
-- modifiee.

CREATE TABLE public.creneaux_disponibilite (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personnel_id      BIGINT       NOT NULL REFERENCES public.users (id),
    date_heure_debut  TIMESTAMP    NOT NULL,
    date_heure_fin    TIMESTAMP    NOT NULL,
    reserve           BOOLEAN      NOT NULL DEFAULT FALSE,
    date_creation     TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_creneau_horaire CHECK (date_heure_fin > date_heure_debut)
);

CREATE INDEX idx_creneau_personnel_debut ON public.creneaux_disponibilite (personnel_id, date_heure_debut);

CREATE TABLE public.rendez_vous (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creneau_id            BIGINT       NOT NULL REFERENCES public.creneaux_disponibilite (id),
    demandeur_id          BIGINT       NOT NULL REFERENCES public.users (id),
    modalite              VARCHAR(20)  NOT NULL,
    lieu_ou_lien          VARCHAR(300),
    motif                 VARCHAR(1000),
    statut                VARCHAR(30)  NOT NULL DEFAULT 'EN_ATTENTE',
    date_heure_proposee_debut TIMESTAMP,
    date_heure_proposee_fin   TIMESTAMP,
    commentaire_reponse   VARCHAR(1000),
    date_creation         TIMESTAMP    NOT NULL DEFAULT now(),
    date_reponse          TIMESTAMP
);

CREATE INDEX idx_rdv_demandeur ON public.rendez_vous (demandeur_id, date_creation DESC);
CREATE INDEX idx_rdv_creneau ON public.rendez_vous (creneau_id);
